#!/usr/bin/env python3
"""Library item facts (Lisa, 21 Nov 2026): the book facts on each Library item page - author, year, publisher, ISBN,
in print or not, and the Stockholm library check - come from Lisa's "AFTERPARTY Library stocktake.xlsx" (NightFever/Libary
on her Mac). Run it again after every stocktake update:

    python3 scripts/library-facts.py "<path to AFTERPARTY Library stocktake.xlsx>" > src/data/library-facts.ts

Only what a visitor should see goes in: no reservation or pickup notes, no catalogue links (outside links rule)."""
import json, re, sys
import openpyxl

wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
facts = {}
for sheet in ("In print", "Out of print"):
    for r in wb[sheet].iter_rows(min_row=2, values_only=True):
        title, author, year, publisher, isbn, status = r[1:7]
        page = r[15]
        if not title or not page:
            continue
        slug = page.rstrip("/").rsplit("/", 1)[-1]
        # "Random House (1993); University of Wisconsin Press (this ISBN)" -> "Random House"
        pub = re.sub(r"\s*\([^)]*\)", "", str(publisher or "").split(";")[0]).strip() or None
        yes = lambda v: str(v or "").strip().lower().startswith("yes")
        other = str(r[16] or "").strip()
        other = None if (not other or other.lower().startswith("none")) else other
        asked = bool(re.search(r"suggest", str(r[17] or ""), re.I))
        facts[slug] = {
            "title": str(title),
            "author": str(author or "").strip() or None,
            "year": int(year) if isinstance(year, (int, float)) else (int(year) if str(year or "").isdigit() else None),
            "publisher": pub,
            "isbn": re.sub(r"[^0-9X]", "", str(isbn or "")) or None,
            "inPrint": sheet == "In print",
            "status": str(status or sheet).strip(),
            "stockholm": {"kulturhuset": yes(r[11]), "dieselverkstaden": yes(r[9]), "other": other, "asked": asked},
            "checked": str(r[14] or "")[:10] or None,
        }

print("// Generated by scripts/library-facts.py from Lisa's AFTERPARTY Library stocktake (NightFever/Libary) - don't edit by hand,")
print("// run the script again after a stocktake. Keyed by A–Z card slug. Shown on Library item pages (src/components/library-item.tsx).")
print()
print("export type BookFacts = {")
print("  title: string;")
print("  author: string | null;")
print("  year: number | null;")
print("  publisher: string | null;")
print("  isbn: string | null;")
print("  inPrint: boolean;")
print("  /** The stocktake's print status, e.g. \"In print (as Party Monster)\" */")
print("  status: string;")
print("  /** Stockholm libraries: Kulturhuset (Kulturbiblioteket), Dieselverkstaden (Nacka), other libraries in the county via Libris, and whether the AFTERPARTY has asked a library to buy it. */")
print("  stockholm: { kulturhuset: boolean; dieselverkstaden: boolean; other: string | null; asked: boolean };")
print("  checked: string | null;")
print("};")
print()
print("export const BOOK_FACTS: Record<string, BookFacts> = " + json.dumps(facts, ensure_ascii=False, indent=2) + ";")
